#!/usr/bin/env python3
"""Fill docs/paper/draft.template.md with numbers from the committed evidence.

Numbers come from docs/figures/numbers.tex (generated by `agenticqa eval-plot`) plus a few values
computed here directly from the report JSON files named in docs/figures/evidence.json. A placeholder
that cannot be resolved is an error: the draft must never contain a number typed by hand.

    PYTHONPATH=src python docs/paper/build_draft.py
"""

from __future__ import annotations

import json
import re
import statistics as st
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

from agenticqa.eval.routing_analysis import analyze  # noqa: E402

SUPERSCRIPT = {"-": "\u207b", "0": "\u2070", "1": "\u00b9", "2": "\u00b2", "3": "\u00b3", "4": "\u2074",
               "5": "\u2075", "6": "\u2076", "7": "\u2077", "8": "\u2078", "9": "\u2079"}


def pfmt(s: str) -> str:
    """'3.8e-06' -> '3.8×10⁻⁶'; plain decimals are returned unchanged."""
    m = re.fullmatch(r"([0-9.]+)e([+-]?)0*(\d+)", s)
    if not m:
        return s
    exp = ("-" if m.group(2) == "-" else "") + m.group(3)
    return f"{m.group(1)}\u00d710" + "".join(SUPERSCRIPT[c] for c in exp)


def load(rel: str) -> dict:
    return json.loads((ROOT / rel).read_text())


def main() -> int:
    macros = dict(re.findall(r"\\newcommand\{\\(\w+)\}\{(.*?)\}", (ROOT / "docs/figures/numbers.tex").read_text()))
    ev = load("docs/figures/evidence.json")
    v: dict[str, object] = dict(macros)

    for k in ("mutPVsUnit", "mutPVsUnitProp", "mutPVsUnitAdv", "injFlakyP"):
        v[k + "F"] = pfmt(macros[k])

    # E5 cost and latency: the median per model, then the range across models
    walls, toks = [], []
    for rel in ev["injection"].values():
        sc = load(rel)["scenarios"]
        walls.append(st.median(s["wall_seconds"] for s in sc))
        toks.append(st.median(s["llm_usage"]["total_tokens"] for s in sc))
    v.update(wallMin=round(min(walls)), wallMax=round(max(walls)),
             tokMin=f"{min(toks) / 1000:.1f}k", tokMax=f"{max(toks) / 1000:.1f}k")
    v["injRoutingOther"] = int(macros["injRoutingFlips"]) - int(macros["injMisdirectFlips"])
    v["injRoutingOtherN"] = int(macros["injRuns"]) - int(macros["injMisdirectN"])

    for name in ("click", "attrs"):  # real suites
        c = load(ev["adversary_real"][name]["after"])["cases"][0]
        v[f"{name}Tests"], v[f"{name}BaseFail"] = f"{c['baseline_total']:,}", c["baseline_failed"]

    v["advRealTotal"] = int(macros["advRealClickCases"]) + int(macros["advRealAttrsCases"])
    pre = load(ev["adversary_real"]["click"]["before"])["summary"]
    v.update(advRealClickI1Before=pre["i1_verdict_violations"], advRealClickI2Before=pre["i2_failure_count_violations"],
             advRealClickI3Before=pre["i3_coverage_violations"])
    v["injControlWithFailures"] = sum(load(rel)["injection"]["control"]["n_with_failures"]
                                      for rel in ev["injection"].values())

    for key, idx in (("invTests", 0), ("supTests", 1)):  # demo test counts
        v[key] = load(ev["catch_matrix"][idx][1])["scenarios"][0]["n_discovered"]

    routing_reports = [load(rel) for rel in ev["routing"]]  # routing set
    a = analyze(routing_reports)
    gpt4o = next(r for r in routing_reports if r["router"] == "openai-gpt-4o")
    rows = gpt4o["samples"]
    repos = {(r["repo"], r["label"]) for r in rows}
    v.update(routRepos=len(repos), routAgenticRepos=sum(1 for _, lab in repos if lab == "agentic"),
             routPlainRepos=sum(1 for _, lab in repos if lab == "plain_service"),
             routTokensPerCommit=f"{gpt4o['provenance']['llm_calls']['total_tokens'] / len(rows) / 1000:.1f}k",
             diffTruncatedPct=round(100 * sum(r["diff_chars"] > 6000 for r in rows) / len(rows)),
             voteGptO=f"{100 * a['routers']['openai-gpt-4o']['repo_vote']['rate']:.1f}")

    sc = load(ev["agentic_heuristic"])["scenarios"]  # heuristic router on the agentic tier
    bugs = [s for s in sc if s["expected_verdict"] == "needs_human_review"]
    v.update(heurAgenticN=len(sc), heurAgenticKinds=sum(s["routing"]["repo_kind_correct"] for s in sc),
             heurAgenticBugs=len(bugs),
             heurAgenticFlagged=sum(s["actual_verdict"] == "needs_human_review" for s in bugs))

    # ---- real-project table, noise table and notes (built from the reports named in the manifest)
    rows = ["| Project | Tests | Failing before any attack | Attack cases | Broken guarantees |", "|---|---|---|---|---|"]
    note = ""
    for entry in ev.get("real_suites", []):
        rep = load(entry["report"])
        if rep.get("could_not_run"):
            rows.append(f"| {entry['name']} | n/a | n/a | could not run | n/a |")
            note = (f"`{entry['name']}` could not run: {rep['reason'][:160]}.")
            continue
        c0 = rep["cases"][0]
        rows.append(f"| {entry['name']} | {c0['baseline_total']:,} | {c0['baseline_failed']} | "
                    f"{rep['summary']['n_cases']} | **{rep['summary']['violations']}** |")
        if entry.get("earlier_failure_report"):
            note = (f"`{entry['name']}` could not run the first time. Its suite has so many parametrized tests that "
                    "passing every test id on the command line failed with \"Argument list too long\". "
                    "We fixed this (Section 6.3) and ran it again. The numbers here are from the second run.")
    v["realSuitesTable"] = "\n".join(rows)
    v["realSuitesList"] = ", ".join(f"{e['name']} ({load(e['report'])['cases'][0]['baseline_total']:,} tests)"
                                    for e in ev.get("real_suites", []) if not load(e["report"]).get("could_not_run"))
    v["packagingNote"] = note

    noise_rows = ["| Router | Decision changed | Share | 95% interval (resampling descriptions) |", "|---|---|---|---|"]
    label = {"openai-gpt-4o-mini": "gpt-4o-mini", "openai-gpt-4o": "gpt-4o",
             "mistral-mistral-large-latest": "mistral-large", "mistral-mistral-small-latest": "mistral-small"}
    for rel in ev.get("route_noise", []):
        rep = load(rel)
        if not rep.get("valid", True):
            continue
        s_ = rep["summary"]
        lo, hi = s_["cluster_by_description"]["ci95"]
        noise_rows.append(f"| {label.get(rep['router'], rep['router'])} | {s_['flips']} of {s_['calls']} | "
                          f"{100 * s_['flip_rate']:.1f}% | [{100 * lo:.1f}, {100 * hi:.1f}] |")
    v["noiseTable"] = "\n".join(noise_rows)
    if "noiseFlips" in macros:
        v["noisePooledPct"] = f"{100 * int(macros['noiseFlips']) / int(macros['noiseCalls']):.1f}"
    v["injRoutingOtherPct"] = f"{100 * v['injRoutingOther'] / v['injRoutingOtherN']:.1f}"

    if "field_study" in ev:
        fs = load(ev["field_study"])["summary"]
        names = {"ran": "Ran end to end", "collection_failed": "Tests could not be collected",
                 "build_or_run_failed": "Environment could not be built or run", "no_tests": "No tests in the repository"}
        rows = ["| Outcome | Attempts |", "|---|---|"]
        for key in ("ran", "collection_failed", "build_or_run_failed", "no_tests"):
            rows.append(f"| {names[key]} | {fs['funnel'].get(key, 0)} |")
        rows.append(f"| **Total** | **{fs['attempted']}** |")
        v["fieldFunnelTable"] = "\n".join(rows)
        rows = ["| Why it did not run | Attempts |", "|---|---|"]
        for why, n in sorted(fs["failure_reasons"].items(), key=lambda kv: -kv[1]):
            rows.append(f"| {why[0].upper() + why[1:]} | {n} |")
        v["fieldReasonsTable"] = "\n".join(rows)

    template = (ROOT / "docs/paper/draft.template.md").read_text()
    v["lessonsCount"] = (len(re.findall(r"^\| \d+ \| ", template, flags=re.M))
                        + len(re.findall(r"^- \*\*\d+\.\*\* ", template, flags=re.M)))
    wanted = set(re.findall(r"\{\{(\w+)\}\}", template))
    missing = sorted(k for k in wanted if k not in v)
    if missing:
        print("UNRESOLVED placeholders:", ", ".join(missing), file=sys.stderr)
        return 1
    out = re.sub(r"\{\{(\w+)\}\}", lambda m: str(v[m.group(1)]), template)
    (ROOT / "docs/paper/draft.md").write_text(out)
    print(f"wrote docs/paper/draft.md: {len(out.split())} words, {len(wanted)} distinct numbers substituted")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

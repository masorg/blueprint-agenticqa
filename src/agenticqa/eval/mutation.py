"""Mutation experiment: does each pyramid layer kill mutants the others cannot?

Hand-seeded bugs (a handful) cannot show that every layer is necessary, only
that it can be. This scales the evidence: mutants of the demo services are
generated by AST-based operators, each is run through the real pipeline with
ground-truth routing, and *which layers fail* is observed, not labelled.

Reading the result: a mutant is **killed** by a layer when that layer ends
FAILED (an ERROR - the mutant broke collection or timed out - makes the mutant
**invalid**, not killed). A layer's **unique kills** are mutants no other layer
kills; they are exactly what the pyramid would lose without it. A **survivor**
is killed by no layer: an equivalent mutant or a blind spot of the whole suite
- we cannot tell which automatically, so claims about necessity use killed
mutants only.

Sampling is stratified by operator with a fixed seed so the selection cannot be
cherry-picked, and Hypothesis runs with a fixed seed so property-layer kills
are reproducible (a stated caveat: they are seed-dependent).
"""

from __future__ import annotations

import ast
import random
import shutil
import tempfile
from collections import defaultdict
from dataclasses import dataclass, field
from pathlib import Path

from ..models.enums import LayerId

HYPOTHESIS_SEED = 0
_CMP_FLIP = {ast.Lt: "<=", ast.LtE: "<", ast.Gt: ">=", ast.GtE: ">", ast.Eq: "!=", ast.NotEq: "=="}
_CMP_TOKEN = {ast.Lt: "<", ast.LtE: "<=", ast.Gt: ">", ast.GtE: ">=", ast.Eq: "==", ast.NotEq: "!="}
_ARITH_SWAP = {ast.Add: ("+", "-"), ast.Sub: ("-", "+")}


@dataclass(frozen=True)
class Site:
    """One mutation: replace bytes [start, end) of the source with ``replacement``."""

    operator: str
    line: int
    start: int
    end: int
    original: str
    replacement: str

    @property
    def description(self) -> str:
        return f"{self.operator} @L{self.line}: {self.original!r} -> {self.replacement!r}"


# --------------------------------------------------------------------------- #
# Enumerating mutation sites
# --------------------------------------------------------------------------- #
def _excluded_lines(tree: ast.AST) -> set[int]:
    """Lines that must not be mutated: bug-toggle plumbing, test-data seeding,
    docstrings. Mutating them produces equivalent mutants or edits the fixtures."""
    skip: set[int] = set()

    def calls_flag(node: ast.AST) -> bool:
        return any(
            isinstance(n, ast.Call) and isinstance(n.func, ast.Name) and n.func.id.startswith(("_bug", "_flag"))
            for n in ast.walk(node)
        )

    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            if node.name.startswith(("_bug", "_flag")) or node.name == "reset_state":
                skip.update(range(node.lineno, (node.end_lineno or node.lineno) + 1))
            doc = ast.get_docstring(node, clean=False)
            if doc is not None and node.body and isinstance(node.body[0], ast.Expr):
                skip.update(range(node.body[0].lineno, (node.body[0].end_lineno or 0) + 1))
        if isinstance(node, (ast.If, ast.IfExp)) and calls_flag(node.test):
            skip.update(range(node.lineno, (node.end_lineno or node.lineno) + 1))
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            skip.add(node.lineno)
        if isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant) and isinstance(node.value.value, str):
            skip.update(range(node.lineno, (node.end_lineno or node.lineno) + 1))
    return skip


def enumerate_sites(source: str) -> list[Site]:
    tree = ast.parse(source)
    data = source.encode()
    line_starts = [0]
    for ln in data.splitlines(keepends=True):
        line_starts.append(line_starts[-1] + len(ln))

    def off(line: int, col: int) -> int:
        return line_starts[line - 1] + col

    def span(node: ast.AST) -> tuple[int, int]:
        return off(node.lineno, node.col_offset), off(node.end_lineno, node.end_col_offset)

    skip = _excluded_lines(tree)
    sites: list[Site] = []

    def add(operator: str, node: ast.AST, start: int, end: int, replacement: str) -> None:
        if node.lineno in skip:
            return
        sites.append(Site(operator, node.lineno, start, end, data[start:end].decode(), replacement))

    def token_between(left: ast.AST, right: ast.AST, token: str) -> tuple[int, int] | None:
        """Byte span of `token` in the gap between two operands, if on one line."""
        a, b = off(left.end_lineno, left.end_col_offset), off(right.lineno, right.col_offset)
        gap = data[a:b].decode()
        i = gap.find(token)
        return (a + i, a + i + len(token)) if i >= 0 and "\n" not in gap else None

    for node in ast.walk(tree):
        if isinstance(node, ast.Compare) and len(node.ops) == 1 and type(node.ops[0]) in _CMP_FLIP:
            op = type(node.ops[0])
            t = token_between(node.left, node.comparators[0], _CMP_TOKEN[op])
            if t:
                add("cmp-flip", node, t[0], t[1], _CMP_FLIP[op])
        elif isinstance(node, ast.BinOp) and type(node.op) in _ARITH_SWAP:
            strs = any(isinstance(x, ast.Constant) and isinstance(x.value, str) for x in (node.left, node.right))
            if not strs and not isinstance(node.left, ast.JoinedStr):
                old, new = _ARITH_SWAP[type(node.op)]
                t = token_between(node.left, node.right, old)
                if t:
                    add("arith-swap", node, t[0], t[1], new)
        elif isinstance(node, ast.BoolOp) and len(node.values) == 2:
            old, new = ("and", "or") if isinstance(node.op, ast.And) else ("or", "and")
            t = token_between(node.values[0], node.values[1], old)
            if t:
                add("bool-swap", node, t[0], t[1], new)
        elif isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.Not):
            s, e = span(node)
            os_, oe = span(node.operand)
            add("not-drop", node, s, e, data[os_:oe].decode())
        elif isinstance(node, ast.Raise) and node.lineno == node.end_lineno:
            s, e = span(node)
            add("raise-drop", node, s, e, "pass")
        elif isinstance(node, ast.If):
            s, e = span(node.test)
            add("if-negate", node.test, s, e, f"not ({data[s:e].decode()})")
        elif (
            isinstance(node, ast.Constant)
            and isinstance(node.value, (int, float))
            and not isinstance(node.value, bool)
        ):
            s, e = span(node)
            new = node.value + 1
            add("const-shift", node, s, e, repr(new))
    return sorted(sites, key=lambda s: (s.line, s.start))


def apply_site(source: str, site: Site) -> str:
    data = source.encode()
    return (data[: site.start] + site.replacement.encode() + data[site.end :]).decode()


def is_valid_python(source: str) -> bool:
    try:
        compile(source, "<mutant>", "exec")
    except (SyntaxError, ValueError):
        return False
    return True


def sample_sites(sites: list[Site], n: int, seed: int) -> list[Site]:
    """Stratified by operator: round-robin over operators (each shuffled by the
    seed) until n are chosen, so no operator dominates and the draw is fixed."""
    rng = random.Random(seed)
    by_op: dict[str, list[Site]] = defaultdict(list)
    for s in sites:
        by_op[s.operator].append(s)
    for lst in by_op.values():
        rng.shuffle(lst)
    ops = sorted(by_op)
    chosen: list[Site] = []
    while len(chosen) < n and any(by_op.values()):
        for op in ops:
            if by_op[op] and len(chosen) < n:
                chosen.append(by_op[op].pop())
    return sorted(chosen, key=lambda s: (s.line, s.start))



@dataclass(frozen=True)
class System:
    name: str
    demo_dir: str  # relative to the agentic-qa repo root
    source_file: str  # the file under mutation
    repo_kind: str  # ground-truth routing: plain_service | agentic


SYSTEMS = {
    "inventory": System("inventory", "demo/inventory-orders-api", "app.py", "plain_service"),
    "support": System("support", "demo/support-assistant", "assistant.py", "agentic"),
}


@dataclass
class MutantResult:
    system: str
    id: str
    operator: str
    line: int
    description: str
    states: dict[str, str] = field(default_factory=dict)  # layer -> state
    failed_tests: int = 0

    @property
    def valid(self) -> bool:
        return not any(s == "error" for s in self.states.values())

    @property
    def killers(self) -> list[str]:
        return [layer for layer, s in self.states.items() if s == "failed"] if self.valid else []

    @property
    def status(self) -> str:
        if not self.valid:
            return "invalid"
        return "killed" if self.killers else "survived"


async def run_mutants(
    system: System, sites: list[Site], *, repo_root: Path, progress=print
) -> list[MutantResult]:
    from ..orchestrator.stubs import HeuristicClassifier, HeuristicTriage
    from .corpus import Scenario
    from .harness import run_scenario
    from .routers import OracleRouter

    demo = repo_root / system.demo_dir
    original = (demo / system.source_file).read_text()
    results: list[MutantResult] = []
    for i, site in enumerate(sites):
        mutated = apply_site(original, site)
        rid = f"{system.name}-{i:03d}"
        if not is_valid_python(mutated):
            results.append(MutantResult(system.name, rid, site.operator, site.line, site.description,
                                        states={"unit": "error"}))
            continue
        tmp = Path(tempfile.mkdtemp(prefix="aqa-mutant-"))
        try:
            work = tmp / "repo"
            shutil.copytree(demo, work, ignore=shutil.ignore_patterns(
                "__pycache__", ".pytest_cache", ".hypothesis", ".venv", ".git"))
            (work / system.source_file).write_text(mutated)
            scenario = Scenario(
                name=f"mut-{rid}", repo_path=str(work), expected_repo_kind=system.repo_kind,
                expected_verdict="needs_human_review",
                extra_env={"PYTEST_ADDOPTS": f"--hypothesis-seed={HYPOTHESIS_SEED}"},
            )
            r = await run_scenario(
                scenario, router=OracleRouter([scenario]), classifier=HeuristicClassifier(),
                triage=HeuristicTriage(), repo_root=repo_root,
            )
            states = {
                layer.value: (r.run.layer_runs[layer].state.value if layer in r.run.layer_runs else "n/a")
                for layer in LayerId.ordered()
            }
            res = MutantResult(system.name, rid, site.operator, site.line, site.description,
                               states=states, failed_tests=r.run.totals["failed"])
        finally:
            shutil.rmtree(tmp, ignore_errors=True)
        results.append(res)
        progress(f"[{system.name} {i + 1}/{len(sites)}] {res.status:8s} {res.killers or ''} {site.description}")
    return results



# Summary
# --------------------------------------------------------------------------- #
def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    """95% Wilson score interval for a proportion k/n."""
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    d = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / d
    half = z * ((p * (1 - p) / n + z * z / (4 * n * n)) ** 0.5) / d
    return (max(0.0, centre - half), min(1.0, centre + half))


BASELINES = {
    "unit-only": ["unit"],
    "unit+adversarial": ["unit", "adversarial"],  # scope-style: component tests + boundary tests
    "unit+property": ["unit", "property"],
    "full-pyramid": ["unit", "property", "trajectory", "llm_judge", "adversarial"],
}


def sign_test_p(b: int, c: int) -> float:
    """Exact two-sided sign test on the discordant pairs (b: only A kills, c: only B kills)."""
    from math import comb

    n = b + c
    if n == 0:
        return 1.0
    k = min(b, c)
    return min(1.0, 2 * sum(comb(n, i) for i in range(k + 1)) / 2**n)


def summarize(results: list[MutantResult]) -> dict:
    valid = [r for r in results if r.valid]
    killed = [r for r in valid if r.killers]
    layers = [layer.value for layer in LayerId.ordered()]

    def rate(k: int, n: int) -> dict:
        lo, hi = wilson(k, n)
        return {"k": k, "n": n, "rate": (k / n) if n else None, "ci95": [round(lo, 3), round(hi, 3)]}

    per_layer = {}
    for layer in layers:
        kills = [r for r in killed if layer in r.killers]
        unique = [r for r in kills if r.killers == [layer]]
        per_layer[layer] = {"kills": len(kills), "unique_kills": len(unique),
                            "unique_ids": [r.id for r in unique]}

    baselines = {
        name: rate(sum(1 for r in killed if set(r.killers) & set(ls)), len(valid))
        for name, ls in BASELINES.items()
    }
    # Same mutants for every baseline, so compare them *paired*: only the
    # discordant mutants (killed by exactly one side) carry information.
    full = set(BASELINES["full-pyramid"])
    paired = {}
    for name, ls in BASELINES.items():
        if name == "full-pyramid":
            continue
        only_full = sum(1 for r in killed if set(r.killers) & full and not set(r.killers) & set(ls))
        only_base = sum(1 for r in killed if set(r.killers) & set(ls) and not set(r.killers) & full)
        paired[name] = {"only_full": only_full, "only_baseline": only_base,
                        "p_value": sign_test_p(only_full, only_base)}
    by_op: dict[str, dict] = defaultdict(lambda: {"generated": 0, "valid": 0, "killed": 0})
    for r in results:
        by_op[r.operator]["generated"] += 1
        by_op[r.operator]["valid"] += int(r.valid)
        by_op[r.operator]["killed"] += int(bool(r.killers))
    return {
        "n_generated": len(results),
        "n_valid": len(valid),
        "n_invalid": len(results) - len(valid),
        "n_killed": len(killed),
        "n_survived": len(valid) - len(killed),
        "per_layer": per_layer,
        "baselines": baselines,
        "paired_vs_full": paired,
        "by_operator": dict(by_op),
        "survivor_ids": [r.id for r in valid if not r.killers],
    }
